"""坐标、像素中心与位移方向约定（全项目统一，勿各自为政）。

图像数组
--------
图像是二维浮点数组 ``img[y, x]``，形状 ``(H, W)``。

像素中心与坐标单位
------------------
* 坐标单位为 **像素**（不是角秒、不是归一化坐标）。
* 像素 ``img[y, x]`` 的中心位于坐标 ``(x, y)``，
  该像素覆盖 ``[x-0.5, x+0.5) x [y-0.5, y+0.5)``。
* ``x`` 是列号，向右增大；``y`` 是行号，向下增大（与 numpy 索引一致）。

位移方向
--------
帧 k 相对参考帧的位移记为 ``(dx_k, dy_k)``，含义：
参考帧中位于 ``(x0, y0)`` 的目标，在帧 k 中位于 ``(x0 + dx_k, y0 + dy_k)``。
即 **+dx 表示图像内容相对参考帧向 +x 方向移动**。

配准（对齐）
------------
把帧 k 重采样回参考网格的方式为::

    aligned[y, x] = frame_k(y + dy_k, x + dx_k)

即在帧 k 的 ``(x + dx_k, y + dy_k)`` 处双线性插值取值，
目标点由此落回参考坐标 ``(x0, y0)``。

覆盖
----
重采样时采样点落在源图有效域 ``[0, W-1] x [0, H-1]`` 之外的输出像素，
覆盖记为 0、权重记为 0；这些像素**不参与**加权平均，
而不是以 0 值参与（避免边缘被零值稀释）。
"""

PIXEL_CENTER = 0.0  # 像素中心位于整数坐标
